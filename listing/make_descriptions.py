"""Standard KDP product description for every Permit Path state edition.
Usage: python3 listing/make_descriptions.py  -> listing/descriptions.md (KDP-ready HTML per state)
Rules: no year, no dollar amounts, no em or en dashes, no URLs, no pass guarantees."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
NAMES = json.loads((ROOT / "layout/config.json").read_text())["state_names"]
AGENCY = {"PA": "PennDOT", "FL": "FLHSMV", "TX": "Texas DPS", "CA": "California DMV", "NY": "New York DMV",
          "IL": "Illinois Secretary of State", "OH": "Ohio BMV", "MO": "Missouri DOR", "NC": "NCDMV", "SC": "SCDMV",
          "GA": "Georgia DDS", "NJ": "New Jersey MVC", "VA": "Virginia DMV", "AL": "ALEA", "MI": "Michigan Secretary of State"}
# How the two mock exams match the real test (one line, verified in docs/states.md and state/XX/mocks.json)
TEST = {
 "PA": "built like the real Pennsylvania test: 18 questions, 15 correct to pass",
 "FL": "built like the real Florida test: 50 questions, 40 correct to pass",
 "TX": "in the two-part format Texas driver education courses use: 15 road signs and 15 road rules, 70 percent to pass each part",
 "CA": "built like the California test for applicants under 18: 46 questions, 38 correct to pass",
 "NY": "built like the real New York test: 20 questions, 14 correct to pass, including at least 2 of the 4 road sign questions",
 "IL": "built like the real Illinois test: 35 questions, 28 correct to pass",
 "OH": "built like the real Ohio test: 40 questions, 30 correct to pass",
 "MO": "built like the real Missouri exams: a 6-sign test and a 25-question written test",
 "NC": "built like the North Carolina exams: a 12-question sign test plus 25 rules of the road questions",
 "SC": "with 25 questions each, scored at 80 percent (the SCDMV does not publish the test length)",
 "GA": "built like the real two-part Georgia test: 20 road signs and 20 road rules, 15 correct to pass each part",
 "NJ": "built like the real New Jersey test: 50 questions, 40 correct to pass",
 "VA": "built like the real two-part Virginia test: 10 road signs (all 10 to pass), then 30 general questions (24 to pass)",
 "AL": "with 30 questions each, scored at 80 percent (ALEA does not publish the test length)",
 "MI": "in two parts, road rules and road signs, scored at about 70 percent like the Michigan driver education exams",
}

TEMPLATE = """<p><b>Get ready for the {S} permit test with a study guide written from the current {A} driver manual and built around how the test really works.</b></p>
<p>The official manual is long and hard to study from. This book turns every rule you are tested on into short, clear lessons with pictures, memory tips and practice questions after every chapter, so you learn it once and still remember it on test day.</p>
<h4>Inside the book</h4>
<ul>
<li><b>A complete {S} chapter:</b> every step from learner's permit to full license, what to bring, the knowledge, vision and road tests, and the limits that apply to new drivers.</li>
<li><b>12 chapters on the rules of the road:</b> signs, signals and markings, right of way, turns and parking, speed, sharing the road, highway driving, night and bad weather, emergencies, alcohol and drugs, and passing the road test. {S} laws sit in clear boxes right where each topic is taught.</li>
<li><b>About 80 road signs</b>, each explained by shape, color and meaning.</li>
<li><b>Chapter quizzes:</b> 10 questions after every chapter, with answers and explanations.</li>
<li><b>2 full mock exams</b> {T}.</li>
<li><b>Test traps and memory tips</b> that flag the questions people miss most.</li>
<li><b>Supervised driving log</b> to record practice hours with your parent or guardian.</li>
</ul>
<h4>Free with your book</h4>
<ul>
<li><b>500+ online practice questions</b> for {S}, with chapter practice, timed mock tests and road sign pictures in full color.</li>
<li><b>Free ebook download</b> to study on your phone, with every picture in color.</li>
<li><b>Full-color road sign flashcards</b> online.</li>
</ul>
<h4>Who it is for</h4>
<p>Teens getting their first {S} learner's permit, parents helping them practice, and adults or new residents who need to take the {S} knowledge test.</p>
<p><b>Study a chapter a day, take the quiz, then sit both mock exams. When you pass them comfortably, you are ready for test day.</b></p>"""

out = ["# Permit Path KDP product descriptions\n\nPaste the HTML block into the KDP Description field (KDP accepts these tags). Generated by `listing/make_descriptions.py`.\n"]
for c in TEST:
    html = TEMPLATE.format(S=NAMES[c], A=AGENCY[c], T=TEST[c])
    for bad in ("—", "–", "$", "http", "202"):
        assert bad not in html, (c, bad)
    out.append(f"## {NAMES[c]} ({c})  ({len(html)} characters)\n\n```html\n{html}\n```\n")
(ROOT / "listing/descriptions.md").write_text("\n".join(out))
print("ok", max(len(TEMPLATE) + 300, 0))
